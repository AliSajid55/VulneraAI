// Builds a downloadable PDF report for one scan.

import { jsPDF } from "jspdf";

import type { ScanDetail } from "../types";
import { formatDateTime, languageLabel } from "./format";

/** Remove Markdown symbols so the explanation reads cleanly in the PDF. */
function plainText(markdown: string): string {
  return markdown
    .replace(/\r\n?/g, "\n")
    .replace(/```[^\n]*\n?/g, "")
    .replace(/^#{1,6}\s+/gm, "")
    .replace(/\*\*(.*?)\*\*/g, "$1")
    .replace(/(?<!\*)\*([^*\n]+)\*(?!\*)/g, "$1")
    .replace(/`([^`]+)`/g, "$1")
    .replace(/^\s*[*-]\s+/gm, "• ");
}

export function downloadScanPdf(scan: ScanDetail) {
  const doc = new jsPDF({ unit: "pt", format: "a4" });
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 48;
  const contentWidth = pageWidth - margin * 2;
  let y = margin;

  const ensureSpace = (needed: number) => {
    if (y + needed > pageHeight - margin) {
      doc.addPage();
      y = margin;
    }
  };

  const writeLines = (text: string, size: number, font: "helvetica" | "courier" = "helvetica",
    style: "normal" | "bold" = "normal", color: [number, number, number] = [30, 41, 59]) => {
    doc.setFont(font, style);
    doc.setFontSize(size);
    doc.setTextColor(...color);
    const lineHeight = size * 1.45;
    for (const line of doc.splitTextToSize(text, contentWidth) as string[]) {
      ensureSpace(lineHeight);
      doc.text(line, margin, y);
      y += lineHeight;
    }
  };

  const heading = (text: string) => {
    y += 10;
    ensureSpace(30);
    writeLines(text, 13, "helvetica", "bold", [15, 23, 42]);
    doc.setDrawColor(226, 232, 240);
    doc.line(margin, y - 6, pageWidth - margin, y - 6);
    y += 6;
  };

  // Header band
  doc.setFillColor(79, 70, 229);
  doc.rect(0, 0, pageWidth, 70, "F");
  doc.setTextColor(255, 255, 255);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(18);
  doc.text("PolyGuard Scan Report", margin, 42);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.text(`Scan #${scan.id}`, pageWidth - margin, 42, { align: "right" });
  y = 100;

  writeLines(scan.title, 15, "helvetica", "bold", [15, 23, 42]);
  writeLines(formatDateTime(scan.created_at), 10, "helvetica", "normal", [100, 116, 139]);

  // Result
  heading("Result");
  const vulnerable = scan.prediction === "vulnerable";
  writeLines(
    vulnerable ? "Potentially Vulnerable (HIGH RISK)" : "Classified as Safe (LOW RISK)",
    12, "helvetica", "bold", vulnerable ? [225, 29, 72] : [5, 150, 105]
  );

  const facts: Array<[string, string]> = [
    ["Confidence (distance from threshold)", `${(scan.confidence * 100).toFixed(1)}%`],
    ["Vulnerable probability", scan.vulnerable_probability.toFixed(4)],
    ["Decision threshold", (scan.threshold ?? 0.5).toFixed(4)],
    ["Language", languageLabel(scan.language)],
    ["Submitted lines", String(scan.total_lines)],
    ["Model", `GraphCodeBERT${scan.model_version ? ` (${scan.model_version})` : ""}, chunk-based classification`],
  ];
  for (const [label, value] of facts) writeLines(`${label}: ${value}`, 10);

  // Code
  heading("Submitted code");
  writeLines(scan.code.replace(/\t/g, "    "), 8.5, "courier", "normal", [51, 65, 85]);

  // AI explanation
  heading("AI explanation");
  if (scan.ai_explanation.available && scan.ai_explanation.explanation) {
    writeLines(plainText(scan.ai_explanation.explanation), 10);
    if (scan.ai_explanation.model) {
      y += 4;
      writeLines(`Generated by ${scan.ai_explanation.model}. AI guidance may be incomplete or incorrect.`,
        8.5, "helvetica", "normal", [100, 116, 139]);
    }
  } else {
    writeLines("No AI explanation was available for this scan.", 10, "helvetica", "normal", [100, 116, 139]);
  }

  // Footer on every page
  const pages = doc.getNumberOfPages();
  for (let page = 1; page <= pages; page++) {
    doc.setPage(page);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(8);
    doc.setTextColor(148, 163, 184);
    doc.text(
      "This result is an overall assessment and does not guarantee the code is free of vulnerabilities.",
      margin, pageHeight - 24
    );
    doc.text(`${page} / ${pages}`, pageWidth - margin, pageHeight - 24, { align: "right" });
  }

  doc.save(`polyguard-scan-${scan.id}.pdf`);
}
